def check_guess(answer):
    global guessing_game
    if not guessing_game:
        return "❌ لا توجد لعبة تخمين نشطة! اكتب 'تخمين' للبدء"
    if guessing_game["guessed"]:
        return "✅ تم حل اللغز بالفعل!"
    if answer.lower() == guessing_game["item"]:
        guessing_game["guessed"] = True
        return f"🎉 **أحسنت!** الجواب: {guessing_game['item']} 🏆"
    guessing_game["attempts"] -= 1
    if guessing_game["attempts"] <= 0:
        guessing_game["guessed"] = True
        return f"😔 انتهت المحاولات! الجواب: {guessing_game['item']}"
    return f"❌ خطأ! تبقى {guessing_game['attempts']} محاولة"

