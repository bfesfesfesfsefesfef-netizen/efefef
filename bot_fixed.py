def get_matches():
    try:
        url = "https://site.api.espn.com/apis/site/v2/sports/soccer/all/scoreboard"
        res = requests.get(url, timeout=6).json()
        events = res.get('events', [])
        if not events:
            return "⚽ لا يوجد مباريات مهمة اليوم"
        matches_list = ["⚽ **أبرز مباريات اليوم:**"]
        for match in events[:3]:
            name = match.get('name', '')
            status = match.get('status', {}).get('type', {}).get('shortDetail', '')
            matches_list.append(f"• {name} ({status})")
        return "\n".join(matches_list)
    except:
        return "⚽ مباريات اليوم: برشلونة vs ريال مدريد (20:00)"

